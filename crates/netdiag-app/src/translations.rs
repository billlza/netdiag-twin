pub(super) fn tr(lang: Language, text: Text) -> &'static str {
    let index = text as usize;
    assert!(
        index < TEXT_COUNT,
        "translation sentinel has no display text"
    );
    match lang {
        Language::Zh => ZH_TEXT[index],
        Language::En => EN_TEXT[index],
    }
}
